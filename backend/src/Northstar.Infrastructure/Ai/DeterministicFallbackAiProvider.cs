using System.Diagnostics;
using Northstar.Application.Abstractions;
using Northstar.Application.Ai;
using Northstar.Domain;

namespace Northstar.Infrastructure.Ai;

/// <summary>
/// Deterministic development fallback. Produces well-formed, clearly-labelled
/// output without any external model call so the application can be demonstrated
/// and tested without an AI provider. Output is explicitly marked as not being
/// live inference.
/// </summary>
public sealed class DeterministicFallbackAiProvider : IAiProvider
{
    public const string ProviderName = "fallback-deterministic";

    public string Name => ProviderName;

    public bool IsLiveInference => false;

    public Task<AiCallResult<AiTicketSummary>> SummarizeAsync(AiTicketContext context, CancellationToken ct)
    {
        var sw = Stopwatch.StartNew();

        var firstCustomerMessage = context.Conversation
            .FirstOrDefault(m => m.Author == "customer")?.Body;

        var actionsTaken = context.Conversation
            .Where(m => m.Author == "agent")
            .Select(m => Truncate(m.Body, 140))
            .ToList();

        var outstanding = new List<string>();
        if (context.Application is { HasOutstandingDocuments: true } app)
        {
            outstanding.Add("The related application has documents that are not approved.");
        }

        if (context.Conversation.Count == 0 || context.Conversation[^1].Author == "customer")
        {
            outstanding.Add("The customer is awaiting a reply.");
        }

        var keyContext = new List<string>
        {
            $"Category: {context.Category}; Priority: {context.Priority}; Status: {context.Status}."
        };
        if (context.Application is { } a)
        {
            keyContext.Add($"Linked application {a.Reference} is '{a.Status}' for {a.ProductName}.");
        }

        var summary = new AiTicketSummary(
            MainIssue: string.IsNullOrWhiteSpace(firstCustomerMessage)
                ? context.Subject
                : Truncate(firstCustomerMessage!, 240),
            KeyContext: keyContext,
            ActionsTaken: actionsTaken.Count == 0 ? new[] { "No agent action recorded yet." } : actionsTaken,
            OutstandingItems: outstanding,
            CurrentState: $"Ticket is '{context.Status}' with priority '{context.Priority}'.",
            Uncertainties: new[]
            {
                "Generated by the deterministic development fallback, not a live model.",
                "Customer identity and document authenticity are not verified by this summary."
            });

        sw.Stop();
        return Task.FromResult(new AiCallResult<AiTicketSummary>(
            summary, ProviderName, null, false, null, sw.ElapsedMilliseconds));
    }

    public Task<AiCallResult<AiSuggestedResponse>> SuggestResponseAsync(
        AiTicketContext context,
        IReadOnlyList<string> guidance,
        CancellationToken ct)
    {
        var sw = Stopwatch.StartNew();

        var body =
$@"Hello,

Thank you for contacting us about ""{context.Subject}"" (reference {context.TicketReference}).

We have logged your request and are reviewing it. Based on our support guidance:

{string.Join("\n", guidance.Take(3).Select(g => $"- {g}"))}

If we need any further information from you, we will let you know. For your security we will never ask you for your password, one-time passcode, or PIN.

Kind regards,
{context.Category} Support Team";

        var response = new AiSuggestedResponse(
            Subject: $"Re: {context.Subject}",
            Body: body,
            RequiresHumanReview: true,
            Notes: guidance.Concat(new[]
            {
                "Draft produced by the deterministic development fallback. A support agent must review and edit before sending."
            }).ToList());

        sw.Stop();
        return Task.FromResult(new AiCallResult<AiSuggestedResponse>(
            response, ProviderName, null, false, null, sw.ElapsedMilliseconds));
    }

    public Task<AiCallResult<AiSentiment>> AnalyzeSentimentAsync(AiTicketContext context, CancellationToken ct)
    {
        var sw = Stopwatch.StartNew();
        var sentiment = SentimentRules.Analyze(context);
        sw.Stop();

        return Task.FromResult(new AiCallResult<AiSentiment>(
            sentiment, ProviderName, null, false, sentiment.Confidence, sw.ElapsedMilliseconds));
    }

    private static string Truncate(string value, int max) =>
        string.IsNullOrEmpty(value) ? string.Empty : value[..Math.Min(value.Length, max)];
}
